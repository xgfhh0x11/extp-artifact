#!/usr/bin/env python3
"""Generate the family-wise threshold table k_n = sqrt(2) * z_{1-alpha/(2n)}.

    python3 gen_kn_table.py [NMAX] > extp_kn_table.h          (C header)
    python3 gen_kn_table.py [NMAX] --isabelle > CMD_Kn_Table.thy   (Isabelle theory)

Q16.16 fixed point, ROUNDED DOWN: kq16(n) = floor(k_n * 2^16).  The negative
(MI) clause uses kq16/2^16 <= k_n (a lower threshold fires more: safe); the
positive (PMU) clause uses (kq16+1)/2^16 > k_n (a higher threshold fires less:
safe).  n = 0, 1 have no sample standard deviation and are encoded as 0; the
reducer takes n < 2 => mi = 1 as an explicit branch BEFORE any table lookup,
so these entries are never consulted.  The same integers are the values the
Isabelle side (CMD_Kn_Table.thy) and the differential tests use, so every side
shares one constant.

Isabelle side: the table is a `nat list`, so k_lo n >= 0 needs no evaluation
of the list (of_nat); lookups are by `drop n`, so a spot value such as
kq16 9 costs nine rewrite steps, never a traversal of the whole list.  No
`eval` (it is an oracle and would trip CMD_Check's oracle assertion).
"""
import sys
from math import floor
from statistics import NormalDist

ALPHA = 0.05
args = [a for a in sys.argv[1:] if not a.startswith('--')]
NMAX = int(args[0]) if args else 4096
ISA = '--isabelle' in sys.argv

import os as _os
sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from kn_table import kq16, k_n_float as k_n

vals = [kq16(n) for n in range(0, NMAX + 1)]
spot = ", ".join(f"n={n}: {vals[n]/65536:.5f}" for n in (2, 9, 39, 54, 78, 100, 108, 489, 1024, NMAX))

if ISA:
    print("theory CMD_Kn_Table\n  imports Main HOL.Real\nbegin\n")
    print("(* GENERATED by measurements/gen_kn_table.py --isabelle; do not edit.")
    print(f"   kq16 n = floor(k_n * 2^16), k_n = sqrt 2 * z_(1 - {ALPHA}/(2n)), n <= {NMAX};")
    print("   entries 0 and 1 are 0 (no sample standard deviation; the reducer never consults them).")
    print(f"   spot values: {spot} *)\n")
    print(f"definition kn_nmax :: nat where \"kn_nmax = {NMAX}\"\n")
    print("definition kq16_list :: \"nat list\" where\n  \"kq16_list = [")
    for i in range(0, len(vals), 10):
        chunk = ", ".join(str(v) for v in vals[i:i+10])
        print("    " + chunk + ("," if i + 10 < len(vals) else ""))
    print("  ]\"\n")
    print("text \\<open>Lookup by drop (no length computation).  Beyond the table the last (largest)")
    print("      entry is used; the reducer refuses n > kn_nmax anyway (budget), and the bracket")
    print("      axiom of the main theory is stated for n <= kn_nmax only.\\<close>")
    print("definition kq16 :: \"nat \\<Rightarrow> nat\" where")
    print("  \"kq16 n = (case drop n kq16_list of [] \\<Rightarrow> last kq16_list | v # _ \\<Rightarrow> v)\"\n")
    print("text \\<open>The two rational brackets of k_n: k_lo n <= k_n < k_hi n = k_lo n + 2^-16.\\<close>")
    print("definition k_lo :: \"nat \\<Rightarrow> real\" where \"k_lo n = of_nat (kq16 n) / 65536\"")
    print("definition k_hi :: \"nat \\<Rightarrow> real\" where \"k_hi n = k_lo n + 1 / 65536\"\n")
    print("lemma k_lo_nonneg: \"k_lo n \\<ge> 0\"")
    print("  by (simp add: k_lo_def)")
    print("lemma k_hi_pos: \"k_hi n > 0\"")
    print("  using k_lo_nonneg[of n] by (simp add: k_hi_def)")
    print("lemma k_hi_nonneg: \"k_hi n \\<ge> 0\"")
    print("  using k_hi_pos[of n] by simp")
    print("lemma k_lo_le_k_hi: \"k_lo n \\<le> k_hi n\"")
    print("  by (simp add: k_hi_def)\n")
    print("text \\<open>Spot value used by the witnesses (n = 9, the test (a) construction).\\<close>")
    print(f"lemma kq16_9: \"kq16 9 = {vals[9]}\"")
    print("  by (simp add: kq16_def kq16_list_def)\n")
    print("end")
else:
    print("/* extp_kn_table.h — generated by gen_kn_table.py; do not edit.")
    print(f" * k_n = sqrt(2) * z_(1 - {ALPHA}/(2n)), Q16.16, rounded DOWN. n < 2 -> 0 (never consulted:")
    print(" * the reducer takes n < 2 => mi = 1 as an explicit branch before any lookup).")
    print(" * Negative clause uses kq16/2^16 (<= k_n), positive clause (kq16+1)/2^16 (> k_n). */")
    print("#ifndef EXTP_KN_TABLE_H\n#define EXTP_KN_TABLE_H\n#include <stdint.h>")
    print(f"#define EXTP_KN_NMAX {NMAX}u")
    print(f"static const uint32_t extp_kn_q16[EXTP_KN_NMAX + 1] = {{")
    for i in range(0, len(vals), 8):
        print("    " + ", ".join(f"{v}u" for v in vals[i:i+8]) + ",")
    print("};")
    print("/* k for n > EXTP_KN_NMAX: use EXTP_KN_NMAX's value (k_n is increasing in n, so this is smaller = conservative). */")
    print("static inline uint32_t extp_kn(uint32_t n) { return n < 2 ? 0u : extp_kn_q16[n > EXTP_KN_NMAX ? EXTP_KN_NMAX : n]; }")
    print("#endif")
    print(f"/* spot values: {spot} */")
