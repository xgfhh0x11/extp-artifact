#!/usr/bin/env python3
"""Generate the family-wise threshold table k_n = sqrt(2) * z_{1-alpha/(2n)}.

Outputs (stdout):  extp_kn_table.h — Q16.16 fixed point, ROUNDED DOWN
(the conservative direction for the negative MI clause: a smaller k lowers
D_low and makes MI fire more).  n = 0, 1 have no threshold (sample stdev
undefined) and are encoded as 0; callers must treat n < 2 as mi = 1.
The same rationals (k_q16 / 65536) are the values the Isabelle side and the
differential test use, so both sides share one constant.
"""
import sys
from math import floor
from statistics import NormalDist

ALPHA = 0.05
NMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 4096

def k_n(n): return 2 ** 0.5 * NormalDist().inv_cdf(1 - ALPHA / (2 * n))

print("/* extp_kn_table.h — generated by gen_kn_table.py; do not edit.")
print(f" * k_n = sqrt(2) * z_(1 - {ALPHA}/(2n)), Q16.16, rounded DOWN. n < 2 -> 0 (no threshold: mi = 1). */")
print("#ifndef EXTP_KN_TABLE_H\n#define EXTP_KN_TABLE_H\n#include <stdint.h>")
print(f"#define EXTP_KN_NMAX {NMAX}u")
print(f"static const uint32_t extp_kn_q16[EXTP_KN_NMAX + 1] = {{")
vals = [0, 0] + [floor(k_n(n) * 65536) for n in range(2, NMAX + 1)]
for i in range(0, len(vals), 8):
    print("    " + ", ".join(f"{v}u" for v in vals[i:i+8]) + ",")
print("};")
print("/* k for n > EXTP_KN_NMAX: use EXTP_KN_NMAX's value (k_n is increasing in n, so this is smaller = conservative). */")
print("static inline uint32_t extp_kn(uint32_t n) { return n < 2 ? 0u : extp_kn_q16[n > EXTP_KN_NMAX ? EXTP_KN_NMAX : n]; }")
print("#endif")
print("/* spot values:", ", ".join(f"n={n}: {vals[n]/65536:.5f}" for n in (2, 39, 54, 78, 100, 108, 489, 1024, NMAX)), "*/")
